def _compact(text: str) -> str:
    return re.sub(r"\s+", "", text).lower()


_BY_KEY = {_compact(key): s for s in SKILLS for key in (s.id, s.name)}
# 「/技能名」：斜杠前是开头或空白；名字里的空格可写可不写（「/去 AI 味」「/去AI味」都认）
_SLASH = {s.id: re.compile(r"(?:^|(?<=\s))/(?:" + "|".join(
    re.escape(k) for k in sorted({s.name, s.name.replace(" ", ""), s.id}, key=len, reverse=True)) + ")", re.I)
    for s in SKILLS}


def find_skill(raw: Optional[str]) -> Optional[Skill]:
    return _BY_KEY.get(_compact((raw or "").strip().lstrip("/").strip("《》「」\"' ")))


def parse_skills(message: str) -> list[Skill]:
    """消息里「/技能名」点名的技能：认不出的不算，按出现先后排。"""
    hits = []
    for s in SKILLS:
        match = _SLASH[s.id].search(message or "")
        if match:
            hits.append((match.start(), s))
    return [s for _pos, s in sorted(hits, key=lambda h: h[0])]


def named_text(chosen: list[Skill]) -> str:
    return "\n\n".join(f"《{s.name}》\n{s.content}" for s in chosen)


def skill_view(s: Skill) -> dict:
    return {"id": s.id, "name": s.name, "summary": s.summary}
