def writing_lens() -> str:
    lines = [f"{i}. {p.name}：{p.write}" for i, p in enumerate(POINTS, 1)]
    return "\n".join([WRITING_TITLE, PREMISE, WRITING_NOTE, *lines])


def planning_lens() -> str:
    return "\n".join([PLANNING_TITLE, f"- {PREMISE}", *(f"- {p.name}：{p.plan}" for p in POINTS)])


def review_lens() -> str:
    return "\n".join(f"{i}. {p.name}：{p.check}" for i, p in enumerate(POINTS, 1))


def skill_text() -> str:
    blocks = [f"{i}. {p.name}\n- 规划：{p.plan}\n- 落笔：{p.write}\n- 检查：{p.check}" for i, p in enumerate(POINTS, 1)]
    return "\n".join([
        "用在：规划卷纲 / 章纲、写正文、续写改写、审稿，以及作者问「这章为什么不好看」的时候。",
        PREMISE,
        "",
        "\n\n".join(blocks),
        "",
        "章纲里每章有三句「读者线」：读者在等（他最想看到哪件事）、本章兑现（这章给他什么）、信息差（谁被蒙在鼓里，保持还是揭开）。"
        "三种信息差一场戏只让一种当主：读者和主角知道而别人不知道是憋，读者知道而主角不知道是急，主角知道而读者不知道是追。",
    ])
